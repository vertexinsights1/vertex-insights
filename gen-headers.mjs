// Regenerates _headers: one CSP for public pages (listed explicitly so /admin keeps its own, different CSP).
// Run: node scripts/gen-headers.mjs   (the build also warns if a root .html is missing from _headers)
import { readdirSync, writeFileSync } from 'node:fs';
const base = `  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Strict-Transport-Security: max-age=31536000; includeSubDomains
`;
const site = "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; img-src 'self' data: https://*.supabase.co; connect-src 'self'; form-action 'self'; frame-ancestors 'none'; base-uri 'self'; object-src 'none'";
const adm = "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: https://*.supabase.co; connect-src 'self' https://*.supabase.co wss://*.supabase.co; form-action 'self'; frame-ancestors 'none'; base-uri 'self'; object-src 'none'";
const pages = readdirSync('.').filter((f) => f.endsWith('.html'));
const paths = ['/', ...pages.flatMap((f) => [`/${f}`, ...(f === 'index.html' || f === '404.html' ? [] : [`/${f.slice(0, -5)}`])]), '/insights/*'];
let o = '# Generated by scripts/gen-headers.mjs. Do not hand-edit.\n';
for (const p of paths) o += `${p}\n${base}  Content-Security-Policy: ${site}\n\n`;
for (const p of ['/admin', '/admin/*']) o += `${p}\n${base}  Content-Security-Policy: ${adm}\n  Cache-Control: no-store\n  X-Robots-Tag: noindex, nofollow\n\n`;
o += `/assets/*\n  Cache-Control: public, max-age=86400\n\n/.netlify/functions/*\n  Cache-Control: no-store\n`;
writeFileSync('_headers', o);
console.log(`_headers written for ${pages.length} pages`);
